# --- Инициализация и сохранение состояния в БД ---
def init_db():
  with sqlite3.connect(DB_PATH) as conn:
    conn.execute("""
            CREATE TABLE IF NOT EXISTS state (
                key TEXT PRIMARY KEY,
                value TEXT
            )
        """)
    conn.commit()


def get_saved_state():
  try:
    with sqlite3.connect(DB_PATH) as conn:
      cur = conn.cursor()
      cur.execute("SELECT key, value FROM state")
      rows = dict(cur.fetchall())
      saved_date = rows.get("current_date")
      saved_weather = rows.get("current_weather")
      if saved_date and saved_weather:
        return dt.date.fromisoformat(saved_date), saved_weather
  except Exception as e:
    print(f"Ошибка чтения БД: {e}", flush=True)
  return None, None


def save_state(date_obj, weather_text):
  try:
    with sqlite3.connect(DB_PATH) as conn:
      conn.execute(
          "INSERT OR REPLACE INTO state (key, value) VALUES ('current_date', ?)",
          (date_obj.isoformat(),),
      )
      conn.execute(
          "INSERT OR REPLACE INTO state (key, value) VALUES"
          " ('current_weather', ?)",
          (weather_text,),
      )
      conn.commit()
  except Exception as e:
    print(f"Ошибка сохранения в БД: {e}", flush=True)


init_db()

# Загружаем сохраненную погоду или генерируем новую
